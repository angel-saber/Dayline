import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../dist/', import.meta.url);
function expand(path, ancestors = new Set()) {
  if (!path.href.startsWith(root.href) || ancestors.has(path.href))
    throw new Error('Invalid or circular stylesheet import: ' + path.href);
  const next = new Set([...ancestors, path.href]);
  return readFileSync(path, 'utf8').replace(
    /@import\s+url\(['"]([^'"]+)['"]\);/g,
    (_rule, specifier) => {
      if (!specifier.startsWith('.')) throw new Error('Styles must use local imports.');
      const child = new URL(specifier, path);
      child.search = '';
      return expand(child, next);
    },
  );
}
const output =
  '/* Generated by npm run build:styles. Edit styles/index.css and its imports. */\n' +
  expand(new URL('styles/index.css', root));
const target = new URL('styles.css', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Stylesheet bundle is stale. Run npm run build:styles.');
} else writeFileSync(target, output);
console.log(
  process.argv.includes('--check')
    ? 'Stylesheet bundle matches its sources.'
    : 'Built one stylesheet without runtime CSS import requests.',
);
